// SPI CPOL=1, CPHA=1 (mode 3), MSB first. Clock idles high.
// Each byte launches 8 cycles. MOSI updates on falling edge;
// MISO samples on rising edge. Pins need not be hardware-SPI mux pins.
// Side-set drives SCLK independently of OUT/IN pins.
static PIO tb_pio = pio1;
static int tb_sm = -1;
static uint tb_program_offset = 0;
static bool tb_ready = false;
static bool tb_sensor_ok = false;
static uint16_t tb_cpi = TRACKBALL_DEFAULT_CPI;
static bool tb_burst_primed = false;

static bool tb_pio_init(void) {
    // 4-instruction program, assembled at runtime to avoid a pioasm dependency.
    // jmp target includes program load offset.
    // Each bit takes approximately 8 PIO cycles with these instructions/delays.
    uint16_t program_instructions[4] = {
        pio_encode_set(pio_x, 7) | pio_encode_sideset(1, 1),
        pio_encode_out(pio_pins, 1) | pio_encode_sideset(1, 0) | pio_encode_delay(2),
        pio_encode_in(pio_pins, 1) | pio_encode_sideset(1, 1) | pio_encode_delay(2),
        0,
    };
    const pio_program_t program = {.instructions = program_instructions, .length = 4, .origin = -1};
    if (!pio_can_add_program(tb_pio, &program)) return false;
    tb_sm = pio_claim_unused_sm(tb_pio, false);
    if (tb_sm < 0) return false;
    tb_program_offset = pio_add_program(tb_pio, &program);
    // Reprogram jump target to the loaded location in instruction memory.
    tb_pio->instr_mem[tb_program_offset + 3] = pio_encode_jmp_x_dec(tb_program_offset + 1) | pio_encode_sideset(1, 1);

    pio_sm_config cfg = pio_get_default_sm_config();
    sm_config_set_wrap(&cfg, tb_program_offset, tb_program_offset + 3);
    sm_config_set_sideset(&cfg, 1, false, false);
    sm_config_set_sideset_pins(&cfg, TRACKBALL_PIN_SCLK);
    sm_config_set_out_pins(&cfg, TRACKBALL_PIN_MOSI, 1);
    sm_config_set_in_pins(&cfg, TRACKBALL_PIN_MISO);
    sm_config_set_out_shift(&cfg, false, true, 8); // shift left; autopull at 8 bits
    sm_config_set_in_shift(&cfg, false, true, 8);  // shift left; autopush at 8 bits
    // ~500 kHz to start, deliberately slower than the PMW3360 maximum.
    // 8 PIO cycles/bit at clockdiv 31.25 => around 500kHz at 125MHz.
    sm_config_set_clkdiv(&cfg, (float)clock_get_hz(clk_sys) / 4000000.0f);

    pio_gpio_init(tb_pio, TRACKBALL_PIN_MOSI);
    pio_gpio_init(tb_pio, TRACKBALL_PIN_MISO);
    pio_gpio_init(tb_pio, TRACKBALL_PIN_SCLK);
    uint32_t outs = (1u << TRACKBALL_PIN_MOSI) | (1u << TRACKBALL_PIN_SCLK);
    pio_sm_set_pins_with_mask(tb_pio, (uint)tb_sm, (1u << TRACKBALL_PIN_SCLK), outs);
    pio_sm_set_pindirs_with_mask(tb_pio, (uint)tb_sm, outs, outs | (1u << TRACKBALL_PIN_MISO));
    pio_sm_init(tb_pio, (uint)tb_sm, tb_program_offset, &cfg);
    pio_sm_clear_fifos(tb_pio, (uint)tb_sm);
    pio_sm_set_enabled(tb_pio, (uint)tb_sm, true);

    gpio_init(TRACKBALL_PIN_NCS);
    gpio_set_dir(TRACKBALL_PIN_NCS, GPIO_OUT);
    gpio_put(TRACKBALL_PIN_NCS, 1);
    tb_ready = true;
    return true;
}

static uint8_t tb_transfer(uint8_t data) {
    // A fixed 8-bit cycle is generated by PIO; CPU just feeds/drains FIFO.
    pio_sm_put_blocking(tb_pio, (uint)tb_sm, (uint32_t)data << 24);
    return (uint8_t)pio_sm_get_blocking(tb_pio, (uint)tb_sm);
}
static void tb_start(void) { gpio_put(TRACKBALL_PIN_NCS, 0); wait_us(1); }
static void tb_end(void) { wait_us(1); gpio_put(TRACKBALL_PIN_NCS, 1); wait_us(20); }

static void tb_write(uint8_t address, uint8_t value) {
    tb_start();
    tb_transfer(address | 0x80);
    tb_transfer(value);
    wait_us(35);
    tb_end();
    wait_us(145);
    if (address != 0x50) tb_burst_primed = false;
}
static uint8_t tb_read(uint8_t address) {
    tb_start();
    tb_transfer(address & 0x7f);
    wait_us(160);
    uint8_t result = tb_transfer(0x00);
    tb_end();
    return result;
}
#ifdef TRACKBALL_LOAD_SROM
static void tb_load_srom(void) {
    tb_write(0x13, 0x1d);
    wait_ms(10);
    tb_write(0x13, 0x18);
    tb_start();
    tb_transfer(0x62 | 0x80);
    wait_us(15);
    for (uint16_t i = 0; i < sizeof(trackball_srom); ++i) {
        tb_transfer(trackball_srom[i]);
        wait_us(15);
    }
    tb_end();
    wait_us(200);
    (void)tb_read(0x2a);
}
#endif

bool pointing_device_driver_init(void) {
    if (!tb_pio_init()) return false;
    tb_start(); wait_us(40); tb_end(); wait_us(40);
    tb_write(0x3a, 0x5a); // Power-Up Reset
    wait_ms(50);
    (void)tb_read(0x02); (void)tb_read(0x03); (void)tb_read(0x04);
    (void)tb_read(0x05); (void)tb_read(0x06);
    uint8_t pid = tb_read(0x00);
    uint8_t inv = tb_read(0x3f);
    uprintf("PMW3360: Product ID=0x%02X Inverse=0x%02X\n", pid, inv);
    if (pid != 0x42 || inv != 0xbd) return false;
#ifdef TRACKBALL_LOAD_SROM
    tb_load_srom();
    uint8_t srom_id = tb_read(0x2a);
    uprintf("PMW3360: SROM ID=0x%02X\n", srom_id);
    if (srom_id == 0x00 || srom_id == 0xFF) return false;
#else
    uprintf("PMW3360: no SROM supplied; tracking may not function reliably\n");
#endif
    tb_write(0x10, 0x00); // Config2
    tb_write(0x0f, (uint8_t)(tb_cpi / 100 - 1)); // CPI
    tb_write(0x63, 0x02); // Lift config
    tb_burst_primed = false;
    tb_sensor_ok = true;
    return true;
}

report_mouse_t pointing_device_driver_get_report(report_mouse_t report) {
    if (!tb_ready || !tb_sensor_ok) return report;
    if (!tb_burst_primed) {
        tb_write(0x50, 0x00); // Prime motion burst
        tb_burst_primed = true;
    }
    tb_start();
    tb_transfer(0x50); // Motion_Burst read command
    wait_us(35);
    uint8_t b[6];
    for (uint8_t i = 0; i < 6; i++) b[i] = tb_transfer(0);
    tb_end();
    if ((b[0] & 0x07) != 0) tb_burst_primed = false;
    if ((b[0] & 0x80) && !(b[0] & 0x08)) {
        int16_t dx = (int16_t)((uint16_t)b[2] | ((uint16_t)b[3] << 8));
        int16_t dy = (int16_t)((uint16_t)b[4] | ((uint16_t)b[5] << 8));
        report.x = CONSTRAIN_HID_XY(-dx);
        report.y = CONSTRAIN_HID_XY(-dy);
    }
    return report;
}
void pointing_device_driver_set_cpi(uint16_t cpi) {
    if (cpi < 100) cpi = 100;
    if (cpi > 12000) cpi = 12000;
    tb_cpi = (cpi / 100) * 100;
    if (tb_sensor_ok) tb_write(0x0f, (uint8_t)(tb_cpi / 100 - 1));
}
uint16_t pointing_device_driver_get_cpi(void) { return tb_cpi; }
